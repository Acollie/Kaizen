package github

import (
	"context"
	"encoding/json"
	"fmt"
	"strings"

	"github.com/alexcollie/kaizen/pkg/review"
)

// defaultReviewBody is used when the summary is empty, since GitHub requires a body for COMMENT reviews
const defaultReviewBody = "Review generated by Kaizen."

// userSource marks a finding the reviewer wrote themselves in the UI
const userSource = "you"

// reviewPayload is the request body for POST /repos/{owner}/{repo}/pulls/{n}/reviews
type reviewPayload struct {
	CommitID string          `json:"commit_id"`
	Event    string          `json:"event"`
	Body     string          `json:"body"`
	Comments []reviewComment `json:"comments"`
}

// reviewComment is one inline comment in a review payload
type reviewComment struct {
	Path      string `json:"path"`
	Line      int    `json:"line"`
	Side      string `json:"side"`
	StartLine int    `json:"start_line,omitempty"`
	StartSide string `json:"start_side,omitempty"`
	Body      string `json:"body"`
}

// reviewResponse is the part of the API response we use
type reviewResponse struct {
	HTMLURL string `json:"html_url"`
}

// Ensure Client satisfies the review.Poster contract
var _ review.Poster = (*Client)(nil)

// PostReview creates a COMMENT review on the PR head commit. Findings that sit on
// a head-side line of a display hunk become inline comments; the rest are listed
// in the review body under "Other findings". If GitHub rejects an inline comment's
// line (HTTP 422), the review is retried once with every finding in the body, and
// the result says so.
func (client *Client) PostReview(ctx context.Context, pr review.PullRequest, files []review.FileDiff, request review.PostRequest) (*review.PostResult, error) {
	if pr.Owner == "" || pr.Repo == "" || pr.Number == 0 || pr.HeadSHA == "" {
		return nil, fmt.Errorf("post review: pull request is missing owner, repo, number or head SHA")
	}

	payload, inlineCount, bodyCount := buildReviewPayload(pr, files, request)
	output, err := client.sendReview(ctx, pr, payload)
	fallback := false
	if err != nil && inlineCount > 0 && isUnresolvableLineError(output, err) {
		payload = bodyOnlyPayload(pr, request)
		inlineCount, bodyCount, fallback = 0, len(request.Findings), true
		output, err = client.sendReview(ctx, pr, payload)
	}
	if err != nil {
		return nil, fmt.Errorf("post review to PR #%d: %w", pr.Number, classifyGHError(err))
	}

	var response reviewResponse
	if err := json.Unmarshal(output, &response); err != nil {
		return nil, fmt.Errorf("parse review response: %w", err)
	}
	return &review.PostResult{URL: response.HTMLURL, InlineComments: inlineCount, BodyFindings: bodyCount, FallbackToBody: fallback}, nil
}

// sendReview POSTs one review payload and returns gh's stdout (the response body,
// which gh also prints for HTTP errors)
func (client *Client) sendReview(ctx context.Context, pr review.PullRequest, payload reviewPayload) ([]byte, error) {
	input, err := json.Marshal(payload)
	if err != nil {
		return nil, fmt.Errorf("encode review payload: %w", err)
	}
	endpoint := fmt.Sprintf("repos/%s/%s/pulls/%d/reviews", pr.Owner, pr.Repo, pr.Number)
	return client.runner().RunWithInput(ctx, client.repoDir(), input, "gh", "api", endpoint, "--method", "POST", "--input", "-")
}

// isUnresolvableLineError reports whether GitHub rejected the review because an
// inline comment's line is not part of the diff it has for the PR
func isUnresolvableLineError(output []byte, err error) bool {
	detail := strings.ToLower(string(output) + " " + errorDetail(err))
	if !strings.Contains(detail, "422") && !strings.Contains(detail, "unprocessable") {
		return false
	}
	return strings.Contains(detail, "line could not be resolved") ||
		strings.Contains(detail, "pull_request_review_thread.line")
}

// bodyOnlyPayload puts every finding in the review body, with no inline comments
func bodyOnlyPayload(pr review.PullRequest, request review.PostRequest) reviewPayload {
	return reviewPayload{
		CommitID: pr.HeadSHA,
		Event:    "COMMENT",
		Body:     reviewBody(request.Summary, request.Findings),
		Comments: []reviewComment{},
	}
}

// buildReviewPayload splits findings into inline comments and body findings and
// returns the payload with the count of each
func buildReviewPayload(pr review.PullRequest, files []review.FileDiff, request review.PostRequest) (reviewPayload, int, int) {
	index := newDiffLineIndex(files)
	comments := []reviewComment{}
	var bodyFindings []review.Finding

	for _, finding := range request.Findings {
		comment, postable := inlineComment(finding, index)
		if postable {
			comments = append(comments, comment)
		} else {
			bodyFindings = append(bodyFindings, finding)
		}
	}

	payload := reviewPayload{
		CommitID: pr.HeadSHA,
		Event:    "COMMENT",
		Body:     reviewBody(request.Summary, bodyFindings),
		Comments: comments,
	}
	return payload, len(comments), len(bodyFindings)
}

// diffLineIndex records, per file, which hunk each commentable head-side line belongs to
type diffLineIndex map[string]map[int]int

func newDiffLineIndex(files []review.FileDiff) diffLineIndex {
	index := make(diffLineIndex, len(files))
	for _, file := range files {
		lines := make(map[int]int)
		for hunkNumber, hunk := range file.Hunks {
			for _, line := range hunk.Lines {
				if line.Kind == review.LineAdded || line.Kind == review.LineContext {
					lines[line.NewLine] = hunkNumber
				}
			}
		}
		index[file.Path] = lines
	}
	return index
}

// hunkFor returns the hunk containing a head-side line, and whether it is commentable
func (index diffLineIndex) hunkFor(path string, line int) (int, bool) {
	hunkNumber, exists := index[path][line]
	return hunkNumber, exists
}

// inlineComment converts a finding to an inline comment when its line (and range
// end, if any) are commentable lines of the same hunk
func inlineComment(finding review.Finding, index diffLineIndex) (reviewComment, bool) {
	if finding.File == "" || finding.Line <= 0 {
		return reviewComment{}, false
	}
	startHunk, startOK := index.hunkFor(finding.File, finding.Line)
	if !startOK {
		return reviewComment{}, false
	}

	comment := reviewComment{
		Path: finding.File,
		Line: finding.Line,
		Side: "RIGHT",
		Body: formatInlineBody(finding),
	}
	if finding.EndLine > finding.Line {
		endHunk, endOK := index.hunkFor(finding.File, finding.EndLine)
		if !endOK || endHunk != startHunk {
			return reviewComment{}, false
		}
		comment.StartLine = finding.Line
		comment.StartSide = "RIGHT"
		comment.Line = finding.EndLine
	}
	return comment, true
}

// isUserComment reports whether the reviewer wrote the finding themselves
func isUserComment(finding review.Finding) bool {
	return finding.Source == userSource
}

// findingHeading renders "**[severity · category] title**" for AI findings. The
// reviewer's own comments have no heading (they are posted as written), except a
// bold title if they gave one.
func findingHeading(finding review.Finding) string {
	if isUserComment(finding) {
		if title := strings.TrimSpace(finding.Title); title != "" {
			return "**" + title + "**"
		}
		return ""
	}
	return fmt.Sprintf("**[%s · %s] %s**", finding.Severity, finding.Category, strings.TrimSpace(finding.Title))
}

// attribution is the trailing line on AI findings the reviewer accepted, so readers
// know where a comment came from. The reviewer's own comments get none.
func attribution(finding review.Finding) string {
	if isUserComment(finding) {
		return ""
	}
	origin := "kaizen review"
	if source := strings.TrimSpace(finding.Source); source != "" {
		origin += " · " + source
	}
	return fmt.Sprintf("<sub>AI-assisted finding (%s), checked by the reviewer</sub>", origin)
}

// joinParagraphs joins the non-empty parts with blank lines
func joinParagraphs(parts ...string) string {
	kept := make([]string, 0, len(parts))
	for _, part := range parts {
		if part != "" {
			kept = append(kept, part)
		}
	}
	return strings.Join(kept, "\n\n")
}

// suggestionBlock renders a GitHub suggestion block, or "" when there is none
func suggestionBlock(finding review.Finding) string {
	if finding.Suggestion == "" {
		return ""
	}
	fence := codeFence(finding.Suggestion)
	return fmt.Sprintf("%ssuggestion\n%s\n%s", fence, strings.TrimRight(finding.Suggestion, "\n"), fence)
}

// formatInlineBody renders an inline comment, with a suggestion block when present
func formatInlineBody(finding review.Finding) string {
	return joinParagraphs(findingHeading(finding), strings.TrimSpace(finding.Body), suggestionBlock(finding), attribution(finding))
}

// reviewBody renders the summary plus the findings that could not be posted inline
func reviewBody(summary string, bodyFindings []review.Finding) string {
	var builder strings.Builder
	builder.WriteString(strings.TrimSpace(summary))

	if len(bodyFindings) > 0 {
		if builder.Len() > 0 {
			builder.WriteString("\n\n")
		}
		builder.WriteString("### Other findings\n")
		for _, finding := range bodyFindings {
			builder.WriteString("\n")
			builder.WriteString(formatBodyFinding(finding))
		}
	}

	if builder.Len() == 0 {
		return defaultReviewBody
	}
	return builder.String()
}

// formatBodyFinding renders one finding as a list item with its location
func formatBodyFinding(finding review.Finding) string {
	lead := findingHeading(finding)
	if location := findingLocation(finding); location != "" {
		lead = strings.TrimSpace(fmt.Sprintf("%s (`%s`)", lead, location))
	}
	var suggestion string
	if finding.Suggestion != "" {
		fence := codeFence(finding.Suggestion)
		suggestion = fmt.Sprintf("%s\n%s\n%s", fence, strings.TrimRight(finding.Suggestion, "\n"), fence)
	}
	rest := joinParagraphs(strings.TrimSpace(finding.Body), suggestion, attribution(finding))
	if lead == "" {
		// A reviewer's PR-level comment: the body itself is the list item
		return "- " + strings.TrimPrefix(indent(rest, "  "), "  ") + "\n"
	}
	if rest == "" {
		return "- " + lead + "\n"
	}
	return "- " + lead + "\n\n" + indent(rest, "  ") + "\n"
}

// findingLocation renders "file", "file:line" or "file:start-end"
func findingLocation(finding review.Finding) string {
	switch {
	case finding.File == "":
		return ""
	case finding.Line <= 0:
		return finding.File
	case finding.EndLine > finding.Line:
		return fmt.Sprintf("%s:%d-%d", finding.File, finding.Line, finding.EndLine)
	default:
		return fmt.Sprintf("%s:%d", finding.File, finding.Line)
	}
}

// codeFence picks a backtick fence longer than any run inside the content
func codeFence(content string) string {
	fence := "```"
	for strings.Contains(content, fence) {
		fence += "`"
	}
	return fence
}

// indent prefixes every non-empty line with prefix
func indent(text, prefix string) string {
	lines := strings.Split(text, "\n")
	for index, line := range lines {
		if line != "" {
			lines[index] = prefix + line
		}
	}
	return strings.Join(lines, "\n")
}
